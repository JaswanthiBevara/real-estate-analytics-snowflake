-- FACT TRASACTION DATA FROM RAW_TRANSACTION SOURCE AND OTHER DIM TABLES
-- FACT TRANSCTION DATA LOADING 

USE DATABASE REAL_ESTATE_ANALYTICS;
USE SCHEMA DW;

INSERT INTO FACT_TRANSACTION
(
    TXN_ID,
    TXN_LINE_ID,

    SK_TXN_DATE,
    SK_CITY,
    SK_DEVELOPER,
    SK_PROPERTY,

    LIST_PRICE,
    SALE_PRICE,
    DISCOUNT_PCT,

    BUYER_SEGMENT,
    CHANNEL,
    TXN_STATUS,
    LOAN_REQ
)
SELECT
    T.TXN_ID,
    T.TXN_LINE_ID,

    D.SK_DATE,
    C.SK_CITY,
    DEV.SK_DEVELOPER,
    P.SK_PROPERTY,

    T.LIST_PRICE_LAKHS,
    T.SALE_PRICE_LAKHS,
    T.DISCOUNT_PCT,

    T.BUYER_SEGMENT,
    T.SALES_CHANNEL,
    T.TXN_STATUS,
    T.LOAN_REQUIRED

FROM RAW.RAW_TRANSACTIONS T

LEFT JOIN DW.DIM_DATE D
    ON D.DATE_VALUE = T.TXN_DATE

LEFT JOIN DW.DIM_CITY C
    ON C.CITY_ID = T.CITY_ID

LEFT JOIN DW.DIM_DEVELOPER DEV
    ON DEV.DEVELOPER_ID = T.DEVELOPER_ID
   AND DEV.IS_CURRENT = TRUE

LEFT JOIN DW.DIM_PROPERTY P
    ON P.PROPERTY_ID = T.PROPERTY_ID
   AND P.IS_CURRENT = TRUE;

SELECT *
FROM DW.FACT_TRANSACTION
ORDER BY TXN_ID, TXN_LINE_ID;

SELECT COUNT(*) AS FACT_ROW_COUNT
FROM DW.FACT_TRANSACTION;



