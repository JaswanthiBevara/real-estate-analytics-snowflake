-- fact transcation data loading

DESC TABLE DW.FACT_TRANSACTION;

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(SK_TXN_DATE) AS DATE_MATCHED,
    COUNT(SK_CITY) AS CITY_MATCHED,
    COUNT(SK_DEVELOPER) AS DEVELOPER_MATCHED,
    COUNT(SK_PROPERTY) AS PROPERTY_MATCHED
FROM DW.FACT_TRANSACTION;

SELECT
    TXN_ID,
    TXN_LINE_ID,
    COUNT(*) AS CNT
FROM DW.FACT_TRANSACTION
GROUP BY
    TXN_ID,
    TXN_LINE_ID
HAVING COUNT(*) > 1;


