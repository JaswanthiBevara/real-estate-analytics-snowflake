FROM TABLE(
    REAL_ESTATE_ANALYTICS.INFORMATION_SCHEMA.COPY_HISTORY(
        TABLE_NAME => 'REAL_ESTATE_ANALYTICS.RAW.RAW_TRANSACTIONS',
        START_TIME => DATEADD('MINUTE', -10, CURRENT_TIMESTAMP())
    )
)
